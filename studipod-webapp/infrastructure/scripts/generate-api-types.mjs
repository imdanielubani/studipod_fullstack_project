/**
 * Generates TypeScript types from the backend's OpenAPI document.
 *
 *   pnpm api:generate <schema-url-or-file>
 *   OPENAPI_SCHEMA_URL=<schema-url-or-file> pnpm api:generate
 *
 * The schema comes from studipod-backend (OpenAPI JSON served next to the /api/docs UI
 * when SWAGGER_ENABLED=true, or an exported file). Output is written to
 * src/types/generated/api-schema.d.ts, which is committed and never edited by hand.
 * See docs/api-integration/api-integration.md.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const ROOT = path.resolve(import.meta.dirname, '../..');
const OUTPUT = path.join(ROOT, 'src/types/generated/api-schema.d.ts');
const BANNER =
  '// Generated by `pnpm api:generate` from the Studipod backend OpenAPI document. Do not edit.\n\n';

function resolveSource(input) {
  if (/^https?:\/\//.test(input)) return new URL(input);
  return pathToFileURL(path.resolve(process.cwd(), input));
}

async function main() {
  const input = process.argv[2] ?? process.env.OPENAPI_SCHEMA_URL;
  if (!input) {
    console.error('Provide the OpenAPI schema URL or file: pnpm api:generate <schema-url-or-file>');
    process.exit(1);
  }

  const ast = await openapiTS(resolveSource(input));
  await mkdir(path.dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, BANNER + astToString(ast));
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
